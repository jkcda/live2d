/**
 * 人设系统提示词。
 *
 * 与代码完全解耦 —— 换人设只需要换这里的数据，不动任何逻辑。
 * 后续接记忆系统时，把召回结果拼在 `buildSystemPrompt()` 的返回值后面即可。
 */

export interface Persona {
  /** 角色名 */
  name: string
  /** 一句话身份设定 */
  identity: string
  /** 说话风格 */
  tone: string
  /** 行为准则，逐条列出 */
  rules: string[]
  /** 额外背景（世界观、口头禅、关系设定等） */
  background?: string
  /**
   * 她能感知到什么。
   *
   * 单独成项而不是塞进 rules：这不是「该怎么说话」的规范，
   * 而是「她具备什么能力」的说明。换人设时这一段可以整个换掉。
   *
   * 留空则完全不提感知能力 —— 用户暂停观察时就是这样，
   * 免得她以为自己看得见、然后凭空编出「我看到你在写代码」。
   */
  perception?: string

  /**
   * 语气标记的说明（[laughter] / [sigh] / [breath]）。
   *
   * 单独成项的理由和 perception 一样：这不是「该怎么说话」的风格规范，
   * 而是**她具备什么能力** —— 合成引擎认得这些标记，写进去声音就真的会笑会叹气。
   *
   * ★ 留空则完全不提。换到不认这些标记的引擎（比如某个不支持的上游）时，
   *   就必须留空 —— 否则她会把这些方括号**原样念出来**，
   *   而那听起来像在念剧本。
   */
  emotion?: string
}

